// computeMimcCommitment computes a MiMC-based commitment
func computeMimcCommitment(coins, energy, pk, rho, rand *big.Int) *big.Int {
	h := zerocash.NewMiMC()
	h.Write(coins.Bytes())
	h.Write(energy.Bytes())
	h.Write(pk.Bytes())
	h.Write(rho.Bytes())
	h.Write(rand.Bytes())
	return new(big.Int).SetBytes(h.Sum(nil))
}

