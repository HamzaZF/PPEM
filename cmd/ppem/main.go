func setupCircuitKeys(participantCount int) (*CircuitKeys, error) {
	simpleCache := cache.NewSimpleCache(".ppem_cache/circuits")
	keys := &CircuitKeys{}
	var err error

	// TX Circuit
	if pk, vk, ccs, found := simpleCache.Load("tx"); found {
		if !quiet {
			printTreeItem(false, "Transaction circuit", "CACHED", 0)
		}
		keys.pkTx, keys.vkTx, keys.ccsTx = pk, vk, ccs
	} else {
		compileStart := time.Now()
		var circuit zerocash.CircuitTx
		keys.ccsTx, err = frontend.Compile(ecc.BW6_761.ScalarField(), r1cs.NewBuilder, &circuit)
		if err != nil {
			return nil, err
		}
		keys.pkTx, keys.vkTx, err = groth16.Setup(keys.ccsTx)
		if err != nil {
			return nil, err
		}
		simpleCache.Save("tx", keys.pkTx, keys.vkTx, keys.ccsTx)
		if !quiet {
			printTreeItem(false, "Transaction circuit", "COMPILED", time.Since(compileStart))
		}
	}

	// Registration Circuit
	if pk, vk, ccs, found := simpleCache.Load("reg"); found {
		if !quiet {
			printTreeItem(false, "Registration circuit", "CACHED", 0)
		}
		keys.pkReg, keys.vkReg, keys.ccsReg = pk, vk, ccs
	} else {
		compileStart := time.Now()
		var circuit register.CircuitTxRegister
		keys.ccsReg, err = frontend.Compile(ecc.BW6_761.ScalarField(), r1cs.NewBuilder, &circuit)
		if err != nil {
			return nil, err
		}
		keys.pkReg, keys.vkReg, err = groth16.Setup(keys.ccsReg)
		if err != nil {
			return nil, err
		}
		simpleCache.Save("reg", keys.pkReg, keys.vkReg, keys.ccsReg)
		if !quiet {
			printTreeItem(false, "Registration circuit", "COMPILED", time.Since(compileStart))
		}
	}

	// Exchange Circuit (dynamic for N participants)
	exchangeName := fmt.Sprintf("exchange_N%d", participantCount)
	if pk, vk, ccs, found := simpleCache.Load(exchangeName); found {
		if !quiet {
			printTreeItem(true, fmt.Sprintf("Exchange circuit [N=%d]", participantCount), "CACHED", 0)
		}
		keys.DynamicManager = &SimpleExchangeManager{
			pk:  pk,
			vk:  vk,
			ccs: ccs,
			n:   participantCount,
		}
	} else {
		compileStart := time.Now()
		circuit := exchange.NewCircuitTxFN(participantCount)
		ccs, err := frontend.Compile(ecc.BW6_761.ScalarField(), r1cs.NewBuilder, circuit)
		if err != nil {
			return nil, fmt.Errorf("exchange circuit compilation failed: %w", err)
		}
		pk, vk, err := groth16.Setup(ccs)
		if err != nil {
			return nil, fmt.Errorf("exchange circuit setup failed: %w", err)
		}
		simpleCache.Save(exchangeName, pk, vk, ccs)
		if !quiet {
			printTreeItem(true, fmt.Sprintf("Exchange circuit [N=%d]", participantCount), "COMPILED", time.Since(compileStart))
		}

		keys.DynamicManager = &SimpleExchangeManager{
			pk:  pk,
			vk:  vk,
			ccs: ccs,
			n:   participantCount,
		}
	}

	return keys, nil
}

